// 教訓をプロンプト末尾に付ける形式
export function formatLessonsBlock(texts) {
  if (!texts || texts.length === 0) return "";
  return `\n\n【過去の訂正から得た教訓 (必ず考慮すること)】\n${texts.map((t, i) => `${i + 1}. ${t}`).join("\n")}`;
}

// 訂正内容から教訓文を生成させるプロンプト
export function buildLessonPrompt(diffs, reason) {
  return `帳票読み取りAIが誤読し、人間が訂正しました。この事例から、今後の読み取りで同じ誤りを防ぐための「一般化された教訓」を1〜2文の日本語で作成してください。

【AIの読み取り → 人間の訂正】
${diffs.map((d) => `- ${d.label}: 「${d.oldValue}」→「${d.newValue}」`).join("\n") || "(表の修正なし)"}

【訂正した人のコメント】
${reason || "(コメントなし)"}

要件: 特定の帳票固有の情報ではなく、他の帳票にも適用できる一般ルールとして簡潔に書く。教訓の本文のみを出力。`;
}
